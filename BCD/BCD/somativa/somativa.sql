CREATE DATABASE biblioteca_som2_JOAO_MOREIRA;

USE biblioteca_som2_JOAO_MOREIRA;


CREATE TABLE USUARIO (
    ID_USUARIO INT PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(120) NOT NULL,
    TELEFONE VARCHAR(20),
    ATIVO BOOLEAN DEFAULT TRUE
);

CREATE TABLE LIVRO(
        ID_LIVRO INT PRIMARY KEY AUTO_INCREMENT,
        TITULO VARCHAR(150) NOT NULL,
        AUTOR VARCHAR(120) NOT NULL,
        EDITORA VARCHAR(100) NOT NULL,
        ISBN CHAR(13) NOT NULL,
        ANO_PUBLICADO INT,
        QUANTIDADE_DISPONIVEL INT DEFAULT 0, CHECK(QUANTIDADE_DISPONIVEL >= 0)
        );
-- O EMPRESTIMO MEU DA 1 NA TA DANDO CERTO
CREATE TABLE EMPRESTIMO(
    ID_EMPRESTIMO INT PRIMARY KEY AUTO_INCREMENT,
    DATA_EMPRESTIMO DATETIME DEFAULT CURRENT_TIMESTAMP,
    DATA_PREVISTA DATE NOT NULL,
    DATA_DEVOLUCAO DATE,
    STATUS_EMPRESTIMO VARCHAR(20) DEFAULT 'ABERTO',
    ID_USUARIO INT NOT NULL,
    ID_LIVRO INT NOT NULL,
    CONSTRAINT FK_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT FK_LIVRO FOREIGN KEY (ID_LIVRO) REFERENCES LIVRO(ID_LIVRO)
);

