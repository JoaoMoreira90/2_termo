CREATE DATABASE CENTRO_DE_TREINAMENTO;

USE CENTRO_DE_TREINAMENTO;

CREATE TABLE ALUNOS(
    ID_ALUNO INT AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(70) NOT NULL,
    CONSTRAINT PK_MATRICULA PRIMARY KEY (ID_ALUNO)
);


CREATE TABLE CURSO(
    ID_CURSO INT AUTO_INCREMENT,
    NOME_CURSO VARCHAR(60) NOT NULL,
    CURSO_CARGA_HORARIA INT
);


CREATE TABLE TURMA(
    ID_TURMA INT AUTO_INCREMENT,
    TURMA_DATA_INICIO DATE NOT NULL,
    DIA_FINAL_TRUMA DATETIME NOT NULL,
);


CREATE TABLE INSTRUTOR(
    ID_INSTRUTOR INT AUTO_INCREMENT,
    NOME_INSTRUTOR VARCHAR(90),
    EMAIL_INSTRUTOR VARCHAR(80),
);



SELECT * FROM alunos;